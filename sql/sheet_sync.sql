-- スプレッドシートの行動予定表を本番の予定（schedules）へ自動で取り込む
-- 設計: docs/sheet-sync-design.md / Vault Projects/field-schedule-manager/Decisions/2026-10-19_行動予定表を本番へ自動で取り込む.md
--
-- 流し方: Supabase の SQL Editor でこのファイルを丸ごと実行（何度流しても同じ結果になる）。
--   そのあと Apps Script の setup() が出すハッシュ値を、いちばん下の「トークンの登録」で入れる。
-- 既存の表は変えない。schedules への書き込みは関数 fsm_sync_sheet_day の中だけ。
--
-- 呼び出し: Apps Script（scripts/sheet-sync/sheet-sync.gs）が anon キーで
--   rpc/fsm_sync_sheet_day { p_token, p_date, p_rows, p_dry_run } を呼ぶ。関数の中でトークンを確かめる。

create extension if not exists pgcrypto with schema extensions;

-- 1) Apps Script のトークン（ハッシュだけ保存する）
create table if not exists public.fsm_ingest_tokens (
  id bigint generated by default as identity primary key,
  name text not null unique,
  token_hash text not null,
  created_at timestamptz not null default now(),
  last_used_at timestamptz
);

-- 2) 予定 ↔ シートの行。前回取り込んだシートの値（synced）を覚えて 3 者比較に使う
create table if not exists public.fsm_sheet_rows (
  schedule_id bigint primary key references public.schedules(id) on delete cascade,
  work_date text not null,
  row_key text not null,
  kind text not null default 'row' check (kind in ('row', 'header')),
  synced jsonb not null,
  missing_since timestamptz,
  conflicts text[] not null default '{}',
  last_seen_at timestamptz not null default now()
);
create index if not exists fsm_sheet_rows_date_idx on public.fsm_sheet_rows (work_date);

-- 3) 取り込みの記録（試しも含む）
create table if not exists public.fsm_sync_runs (
  id bigint generated by default as identity primary key,
  ran_at timestamptz not null default now(),
  work_date text not null,
  dry_run boolean not null,
  sheet_rows int not null default 0,
  inserted int not null default 0,
  linked int not null default 0,
  updated int not null default 0,
  unchanged int not null default 0,
  conflicts int not null default 0,
  cancelled int not null default 0,
  restored int not null default 0,
  removed_header int not null default 0,
  unresolved_staff text[] not null default '{}',
  error text,
  detail jsonb
);
create index if not exists fsm_sync_runs_ran_idx on public.fsm_sync_runs (ran_at desc);

alter table public.fsm_ingest_tokens enable row level security;
alter table public.fsm_sheet_rows enable row level security;
alter table public.fsm_sync_runs enable row level security;
revoke all on public.fsm_ingest_tokens from anon, authenticated;
revoke all on public.fsm_sheet_rows from anon, authenticated;
revoke all on public.fsm_sync_runs from anon, authenticated;
-- 画面に「最終取り込み」と食い違いを出すため、ログインした人は読める
grant select on public.fsm_sync_runs to authenticated;
grant select on public.fsm_sheet_rows to authenticated;
drop policy if exists fsm_sync_runs_select on public.fsm_sync_runs;
create policy fsm_sync_runs_select on public.fsm_sync_runs for select to authenticated using (true);
drop policy if exists fsm_sheet_rows_select on public.fsm_sheet_rows;
create policy fsm_sheet_rows_select on public.fsm_sheet_rows for select to authenticated using (true);

-- 名前をそろえる（空白・異体字・半角カナの記号）
create or replace function public.fsm_norm_name(p text)
returns text
language sql
immutable
as $$
  select translate(regexp_replace(coalesce(p, ''), '[\s　]+', '', 'g'), '﨑髙𠮷', '崎高吉')
$$;

-- 対応者の名寄せ: 完全一致 → 空白・異体字をそろえて一致 → 接頭辞（FE/SF/FR）を除いた苗字の前方一致が 1 人だけ
create or replace function public.fsm_resolve_staff(p_name text)
returns bigint
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_norm text := public.fsm_norm_name(p_name);
  v_id bigint;
  v_cnt int;
begin
  if v_norm = '' then return null; end if;
  select id into v_id from staff where trim(name) = trim(p_name) order by coalesce(is_active, 1) desc, id limit 1;
  if v_id is not null then return v_id; end if;
  select id into v_id from staff where public.fsm_norm_name(name) = v_norm order by coalesce(is_active, 1) desc, id limit 1;
  if v_id is not null then return v_id; end if;
  if char_length(v_norm) >= 2 then
    select count(*), min(id) into v_cnt, v_id from staff
      where public.fsm_norm_name(regexp_replace(name, '^(FE|SF|FR|FTS)', '', 'i')) like regexp_replace(v_norm, '^(FE|SF|FR|FTS)', '', 'i') || '%'
        and (upper(left(v_norm, 2)) not in ('FE', 'SF', 'FR') or upper(left(public.fsm_norm_name(name), 2)) = upper(left(v_norm, 2)));
    if v_cnt = 1 then return v_id; end if;
  end if;
  return null;
end;
$$;

-- 取り込み本体。p_rows はシートの行（上から順）と 1 行目の休暇・社内予定:
--   行:   {"kind":"row","division","type","box","unit_number","property_name","work_type","description","target_time",
--          "staff_name","area","prefecture","transport","co_worker","request_number","result","notes","disorder_type","level","level_3"}
--   1行目: {"kind":"header","label":"休暇"|"健康診断"|…,"staff_name","target_time"}
-- 返り値: 件数のまとめ（試しのときも同じ形。試しでは schedules を変えない）
create or replace function public.fsm_sync_sheet_day(
  p_token text,
  p_date text,
  p_rows jsonb,
  p_dry_run boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_token_name text;
  v_fields text[] := array['division','type','box','unit_number','property_name','work_type','description','target_time',
                           'staff_id','staff_name','area','prefecture','transport','co_worker','request_number','notes',
                           'disorder_type','level','level_3','course','status'];
  v_now timestamptz := now();
  r jsonb;
  i int := 0;
  v_kind text;
  v_raw_staff text;
  v_staff_id bigint;
  v_staff record;
  v_base text;
  v_key text;
  v_seen_keys text[] := '{}';
  v_occ jsonb := '{}';
  v_new jsonb;
  v_save jsonb;
  v_map record;
  v_sched jsonb;
  v_used bigint[] := '{}';
  v_target bigint;
  v_set jsonb;
  v_conf text[];
  f text;
  v_cur text; v_old text; v_nv text;
  v_ins int := 0; v_link int := 0; v_upd int := 0; v_same int := 0; v_cf int := 0;
  v_can int := 0; v_res int := 0; v_rmh int := 0;
  v_unres text[] := '{}';
  v_samples jsonb := '[]';
  v_label text;
  v_wt text;
  v_new_id bigint;
  v_run_id bigint;
begin
  select name into v_token_name from fsm_ingest_tokens
    where token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex');
  if v_token_name is null then
    raise exception 'トークンが正しくありません' using errcode = '42501';
  end if;
  if p_date !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception '日付の形が正しくありません: %', p_date using errcode = '22023';
  end if;
  update fsm_ingest_tokens set last_used_at = v_now where name = v_token_name;

  for r in select value from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb)) loop
    i := i + 1;
    v_kind := coalesce(r->>'kind', 'row');
    v_raw_staff := nullif(trim(coalesce(r->>'staff_name', '')), '');
    v_staff_id := case when v_raw_staff is null then null else fsm_resolve_staff(v_raw_staff) end;
    if v_raw_staff is not null and v_staff_id is null and not (v_raw_staff = any(v_unres)) then
      v_unres := v_unres || v_raw_staff;
    end if;
    select id, name, default_course into v_staff from staff where id = v_staff_id;

    -- シートの値 → 予定の値
    if v_kind = 'header' then
      v_label := coalesce(r->>'label', '');
      v_wt := case when v_label = '休暇' then '休暇' else '社内' end;
      v_new := jsonb_build_object(
        'division', case when v_staff.default_course ~ '^\d+$' and v_staff.default_course::int >= 90 then '委託' else 'FTS' end,
        'type', null, 'box', null, 'unit_number', null,
        'property_name', case when v_wt = '休暇' then '（休暇）' else '（社内用務）' end,
        'work_type', v_wt,
        'description', case when v_wt = '休暇' then null else v_label end,
        'target_time', coalesce(nullif(r->>'target_time', ''), case when v_wt = '休暇' then '終日' else '指定なし' end),
        'staff_id', v_staff_id, 'staff_name', coalesce(v_staff.name, v_raw_staff),
        'area', null, 'prefecture', null, 'transport', null, 'co_worker', null, 'request_number', null,
        'notes', null, 'disorder_type', null, 'level', null, 'level_3', null,
        'course', v_staff.default_course, 'status', 'confirmed');
      v_base := p_date || '|header|' || v_label || '|' || fsm_norm_name(v_raw_staff);
    else
      v_new := jsonb_build_object(
        'division', nullif(r->>'division', ''), 'type', nullif(r->>'type', ''), 'box', nullif(r->>'box', ''),
        'unit_number', nullif(r->>'unit_number', ''),
        'property_name', coalesce(nullif(r->>'property_name', ''), '（物件名なし）'),
        'work_type', nullif(r->>'work_type', ''), 'description', nullif(r->>'description', ''),
        'target_time', nullif(r->>'target_time', ''),
        'staff_id', v_staff_id, 'staff_name', coalesce(v_staff.name, v_raw_staff),
        'area', nullif(r->>'area', ''), 'prefecture', nullif(r->>'prefecture', ''), 'transport', nullif(r->>'transport', ''),
        'co_worker', nullif(r->>'co_worker', ''), 'request_number', nullif(r->>'request_number', ''),
        'notes', nullif(r->>'notes', ''), 'disorder_type', nullif(r->>'disorder_type', ''),
        'level', nullif(r->>'level', ''), 'level_3', nullif(r->>'level_3', ''),
        'course', v_staff.default_course,
        'status', case when trim(coalesce(r->>'result', '')) = 'キャンセル' then 'cancelled' else 'confirmed' end);
      v_base := p_date || '|row|' || coalesce(nullif(fsm_norm_name(r->>'unit_number'), ''), fsm_norm_name(r->>'property_name')) || '|' || fsm_norm_name(v_raw_staff);
    end if;
    v_occ := jsonb_set(v_occ, array[v_base], to_jsonb(coalesce((v_occ->>v_base)::int, 0) + 1));
    v_key := v_base || '#' || (v_occ->>v_base);
    v_seen_keys := v_seen_keys || v_key;

    -- 1) 前回と同じ鍵
    v_target := null;
    select m.schedule_id, m.synced, m.missing_since into v_map
      from fsm_sheet_rows m where m.work_date = p_date and m.row_key = v_key and not (m.schedule_id = any(v_used)) limit 1;
    if found then v_target := v_map.schedule_id; end if;

    -- 2) 鍵は違うが、同じ日・同じ号機（無ければ物件名）で、今回まだ見えていない取り込み済みの行（対応者・時間を変えた行）
    if v_target is null and v_kind = 'row' then
      select m.schedule_id, m.synced, m.missing_since into v_map
        from fsm_sheet_rows m join schedules s on s.id = m.schedule_id
        where m.work_date = p_date and m.kind = 'row' and not (m.schedule_id = any(v_used))
          and not exists (select 1 from unnest(v_seen_keys) k where k = m.row_key)
          and coalesce(nullif(fsm_norm_name(m.synced->>'unit_number'), ''), fsm_norm_name(m.synced->>'property_name'))
              = coalesce(nullif(fsm_norm_name(v_new->>'unit_number'), ''), fsm_norm_name(v_new->>'property_name'))
        order by m.schedule_id limit 1;
      if found then v_target := v_map.schedule_id; end if;
    end if;

    if v_target is not null then
      -- 3 者比較: 前回の値のまま → シートの値で更新 / アプリで直されている → 残す（両方変わったら食い違い）
      select to_jsonb(s) into v_sched from schedules s where s.id = v_target;
      v_set := '{}'; v_conf := '{}';
      foreach f in array v_fields loop
        v_cur := v_sched->>f; v_old := v_map.synced->>f; v_nv := v_new->>f;
        if v_nv is distinct from v_old then
          if v_cur is not distinct from v_old or (f = 'status' and v_map.missing_since is not null) then
            v_set := v_set || jsonb_build_object(f, v_new->f);
          elsif v_cur is distinct from v_nv then
            v_conf := v_conf || f;
          end if;
        elsif f = 'status' and v_map.missing_since is not null and v_cur = 'cancelled' then
          v_set := v_set || jsonb_build_object(f, v_new->f); -- シートに戻ってきた → キャンセルを外す
        end if;
      end loop;
      if v_map.missing_since is not null then v_res := v_res + 1; end if;
      if v_set = '{}'::jsonb and cardinality(v_conf) = 0 then v_same := v_same + 1; else
        if v_set <> '{}'::jsonb then v_upd := v_upd + 1; end if;
        if cardinality(v_conf) > 0 then v_cf := v_cf + 1; end if;
      end if;
      if not p_dry_run then
        if v_set <> '{}'::jsonb then
          update schedules s set
            division = case when v_set ? 'division' then v_set->>'division' else s.division end,
            type = case when v_set ? 'type' then v_set->>'type' else s.type end,
            box = case when v_set ? 'box' then v_set->>'box' else s.box end,
            unit_number = case when v_set ? 'unit_number' then v_set->>'unit_number' else s.unit_number end,
            property_name = case when v_set ? 'property_name' then v_set->>'property_name' else s.property_name end,
            work_type = case when v_set ? 'work_type' then v_set->>'work_type' else s.work_type end,
            description = case when v_set ? 'description' then v_set->>'description' else s.description end,
            target_time = case when v_set ? 'target_time' then v_set->>'target_time' else s.target_time end,
            staff_id = case when v_set ? 'staff_id' then (v_set->>'staff_id')::bigint else s.staff_id end,
            staff_name = case when v_set ? 'staff_name' then v_set->>'staff_name' else s.staff_name end,
            area = case when v_set ? 'area' then v_set->>'area' else s.area end,
            prefecture = case when v_set ? 'prefecture' then v_set->>'prefecture' else s.prefecture end,
            transport = case when v_set ? 'transport' then v_set->>'transport' else s.transport end,
            co_worker = case when v_set ? 'co_worker' then v_set->>'co_worker' else s.co_worker end,
            request_number = case when v_set ? 'request_number' then v_set->>'request_number' else s.request_number end,
            notes = case when v_set ? 'notes' then v_set->>'notes' else s.notes end,
            disorder_type = case when v_set ? 'disorder_type' then v_set->>'disorder_type' else s.disorder_type end,
            level = case when v_set ? 'level' then v_set->>'level' else s.level end,
            level_3 = case when v_set ? 'level_3' then v_set->>'level_3' else s.level_3 end,
            course = case when v_set ? 'course' then v_set->>'course' else s.course end,
            status = case when v_set ? 'status' then v_set->>'status' else s.status end,
            updated_by = 'シート取り込み', updated_at = v_now
          where s.id = v_target;
        end if;
        -- シートの結果が「完了」で、アプリの結果が空なら入れる
        if v_kind = 'row' and trim(coalesce(r->>'result', '')) = '完了' then
          update schedules set result = '完了' where id = v_target and coalesce(result, '') = '';
        end if;
        -- 食い違いの項目は「前回の値」を残す（次の取り込みでも食い違いとして出し続け、アプリかシートでそろうまで消さない）
        v_save := v_new;
        foreach f in array v_conf loop
          v_save := jsonb_set(v_save, array[f], coalesce(v_map.synced->f, 'null'::jsonb));
        end loop;
        update fsm_sheet_rows set row_key = v_key, synced = v_save, missing_since = null, conflicts = v_conf, last_seen_at = v_now
          where schedule_id = v_target;
      end if;
      v_used := v_used || v_target;
      continue;
    end if;

    -- 3) まだ取り込みと結び付いていない既存の予定（手で取り込んだ行）: 同じ日・同じ号機（物件名）・同じ対応者 → 結び付ける
    v_target := null;
    if v_kind = 'row' then
      select s.id into v_target from schedules s
        where s.date = p_date and not (s.id = any(v_used))
          and not exists (select 1 from fsm_sheet_rows m where m.schedule_id = s.id)
          and coalesce(nullif(fsm_norm_name(s.unit_number), ''), fsm_norm_name(s.property_name))
              = coalesce(nullif(fsm_norm_name(v_new->>'unit_number'), ''), fsm_norm_name(v_new->>'property_name'))
          and (s.staff_id is not distinct from v_staff_id or fsm_norm_name(s.staff_name) = fsm_norm_name(v_raw_staff))
        order by s.is_transferred desc, s.id limit 1;
    else
      select s.id into v_target from schedules s
        where s.date = p_date and not (s.id = any(v_used)) and s.work_type = v_new->>'work_type'
          and not exists (select 1 from fsm_sheet_rows m where m.schedule_id = s.id)
          and (s.staff_id is not distinct from v_staff_id and v_staff_id is not null or fsm_norm_name(s.staff_name) = fsm_norm_name(v_raw_staff))
        order by s.id limit 1;
    end if;
    if v_target is not null then
      v_link := v_link + 1;
      if not p_dry_run then
        -- 結び付けた予定は、前回の値＝今の値として登録し、シートの値で上書きする（シートの方が新しい前提）
        select to_jsonb(s) into v_sched from schedules s where s.id = v_target;
        update schedules s set
          division = v_new->>'division', type = v_new->>'type', box = v_new->>'box', unit_number = v_new->>'unit_number',
          property_name = v_new->>'property_name', work_type = v_new->>'work_type', description = v_new->>'description',
          target_time = v_new->>'target_time', staff_id = (v_new->>'staff_id')::bigint, staff_name = v_new->>'staff_name',
          area = v_new->>'area', prefecture = v_new->>'prefecture', transport = v_new->>'transport', co_worker = v_new->>'co_worker',
          request_number = v_new->>'request_number', notes = coalesce(v_new->>'notes', s.notes), disorder_type = v_new->>'disorder_type',
          level = v_new->>'level', level_3 = v_new->>'level_3', course = coalesce(v_new->>'course', s.course),
          status = case when s.status = 'cancelled' and v_new->>'status' <> 'cancelled' then s.status else v_new->>'status' end,
          is_transferred = 1, updated_by = 'シート取り込み', updated_at = v_now
        where s.id = v_target;
        insert into fsm_sheet_rows (schedule_id, work_date, row_key, kind, synced, last_seen_at)
          values (v_target, p_date, v_key, v_kind, v_new, v_now);
      end if;
      v_used := v_used || v_target;
      continue;
    end if;

    -- 4) 新しい予定
    v_ins := v_ins + 1;
    if jsonb_array_length(v_samples) < 5 then
      v_samples := v_samples || jsonb_build_object('staff', v_new->>'staff_name', 'unit', v_new->>'unit_number', 'property', v_new->>'property_name', 'kind', v_kind);
    end if;
    if not p_dry_run then
      insert into schedules (status, division, type, box, unit_number, property_name, work_type, description, target_time, date,
                             staff_id, staff_name, area, prefecture, transport, co_worker, request_number, course, notes,
                             disorder_type, level, level_3, result, sort_order, is_transferred, created_by, updated_by)
      values (v_new->>'status', v_new->>'division', v_new->>'type', v_new->>'box', v_new->>'unit_number', v_new->>'property_name',
              v_new->>'work_type', v_new->>'description', v_new->>'target_time', p_date,
              (v_new->>'staff_id')::bigint, v_new->>'staff_name', v_new->>'area', v_new->>'prefecture', v_new->>'transport',
              v_new->>'co_worker', v_new->>'request_number', v_new->>'course', v_new->>'notes',
              v_new->>'disorder_type', v_new->>'level', v_new->>'level_3',
              case when v_kind = 'row' and trim(coalesce(r->>'result', '')) = '完了' then '完了' else null end,
              i, 1, 'シート取り込み', 'シート取り込み')
      returning id into v_new_id;
      insert into fsm_sheet_rows (schedule_id, work_date, row_key, kind, synced, last_seen_at)
        values (v_new_id, p_date, v_key, v_kind, v_new, v_now);
      v_used := v_used || v_new_id;
    end if;
  end loop;

  -- シートから消えた行: 行はキャンセル（消さない）、1 行目の休暇・社内予定は削除
  for v_map in
    select m.schedule_id, m.kind, m.missing_since from fsm_sheet_rows m
      where m.work_date = p_date and not (m.schedule_id = any(v_used))
        and not exists (select 1 from unnest(v_seen_keys) k where k = m.row_key)
  loop
    if v_map.kind = 'header' then
      v_rmh := v_rmh + 1;
      if not p_dry_run then delete from schedules where id = v_map.schedule_id; end if;
    elsif v_map.missing_since is null then
      v_can := v_can + 1;
      if not p_dry_run then
        update schedules set status = 'cancelled', updated_by = 'シート取り込み', updated_at = v_now where id = v_map.schedule_id;
        update fsm_sheet_rows set missing_since = v_now where schedule_id = v_map.schedule_id;
      end if;
    end if;
  end loop;

  insert into fsm_sync_runs (work_date, dry_run, sheet_rows, inserted, linked, updated, unchanged, conflicts, cancelled, restored,
                             removed_header, unresolved_staff, detail)
    values (p_date, p_dry_run, i, v_ins, v_link, v_upd, v_same, v_cf, v_can, v_res, v_rmh, v_unres,
            jsonb_build_object('samples', v_samples, 'token', v_token_name))
    returning id into v_run_id;

  return jsonb_build_object('date', p_date, 'dry_run', p_dry_run, 'sheet_rows', i,
    'inserted', v_ins, 'linked', v_link, 'updated', v_upd, 'unchanged', v_same, 'conflicts', v_cf,
    'cancelled', v_can, 'restored', v_res, 'removed_header', v_rmh, 'unresolved_staff', to_jsonb(v_unres),
    'samples', v_samples, 'run_id', v_run_id);
end;
$$;

-- 取り込みに失敗したとき（シートが読めない等）の記録
create or replace function public.fsm_sync_error(p_token text, p_date text, p_error text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not exists (select 1 from fsm_ingest_tokens where token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex')) then
    raise exception 'トークンが正しくありません' using errcode = '42501';
  end if;
  insert into fsm_sync_runs (work_date, dry_run, error) values (coalesce(p_date, ''), false, left(coalesce(p_error, ''), 500));
end;
$$;

revoke all on function public.fsm_sync_sheet_day(text, text, jsonb, boolean) from public;
revoke all on function public.fsm_sync_error(text, text, text) from public;
revoke all on function public.fsm_resolve_staff(text) from public, anon;
grant execute on function public.fsm_sync_sheet_day(text, text, jsonb, boolean) to anon, authenticated;
grant execute on function public.fsm_sync_error(text, text, text) to anon, authenticated;
grant execute on function public.fsm_resolve_staff(text) to authenticated;

