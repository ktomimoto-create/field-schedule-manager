-- FE の位置（FE画面を開いている間に送る）。動態マップの FE のピンに使う。
-- FE動態（fe-dotai）の fd_positions_latest / fd_positions / fd_report_position を移したもの。
-- 先に sql/fe_events.sql（fe_my_staff_id を作る）を流しておくこと。
-- 流し方: Supabase の SQL Editor でこのファイルを丸ごと実行。何度流しても同じ結果になる。
--
-- 費用を抑える決まり（画面側）: 50m 以上動いたときか、5 分たったときだけ送る。精度が 100m より悪い測位は捨てる。
-- iPhone の Web は画面ロック中・別アプリ表示中は送れない（ボタンを押したときの位置は fe_events に残る）。

-- いちばん新しい位置（1 人 1 行）
create table if not exists public.fe_positions_latest (
  staff_id bigint primary key references public.staff(id) on delete cascade,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);

-- 位置の履歴（軌跡用。保存期間は運用で決める: 例 90 日）
create table if not exists public.fe_positions (
  id bigint generated by default as identity primary key,
  staff_id bigint not null references public.staff(id) on delete cascade,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);
create index if not exists fe_positions_staff_time_idx on public.fe_positions (staff_id, recorded_at);

alter table public.fe_positions_latest enable row level security;
alter table public.fe_positions enable row level security;

drop policy if exists fe_positions_latest_select_authenticated on public.fe_positions_latest;
create policy fe_positions_latest_select_authenticated on public.fe_positions_latest
  for select to authenticated using (true);
drop policy if exists fe_positions_select_authenticated on public.fe_positions;
create policy fe_positions_select_authenticated on public.fe_positions
  for select to authenticated using (true);

-- 直接の読み書きは anon に許さない。書き込みは RPC だけ
revoke all on public.fe_positions_latest from anon;
revoke all on public.fe_positions from anon;
revoke insert, update, delete on public.fe_positions_latest from authenticated;
revoke insert, update, delete on public.fe_positions from authenticated;
grant select on public.fe_positions_latest to authenticated;
grant select on public.fe_positions to authenticated;

-- ついでに: fe_events も anon からは読めないようにする（RLS で行は見えないが、権限も外しておく）
revoke select on public.fe_events from anon;

-- 位置を送る。誰の位置かはログイン中のメール → staff で決める
create or replace function public.fe_report_position(
  p_lat double precision,
  p_lng double precision,
  p_accuracy_m double precision default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff bigint := public.fe_my_staff_id();
begin
  if v_staff is null then
    raise exception 'このアカウントは担当者の名簿（staff）に登録されていません' using errcode = '42501';
  end if;
  if p_lat is null or p_lng is null or p_lat not between -90 and 90 or p_lng not between -180 and 180 then
    raise exception '位置が正しくありません' using errcode = '22023';
  end if;

  insert into public.fe_positions_latest (staff_id, lat, lng, accuracy_m, recorded_at)
  values (v_staff, p_lat, p_lng, p_accuracy_m, now())
  on conflict (staff_id) do update
    set lat = excluded.lat, lng = excluded.lng, accuracy_m = excluded.accuracy_m, recorded_at = excluded.recorded_at;

  insert into public.fe_positions (staff_id, lat, lng, accuracy_m) values (v_staff, p_lat, p_lng, p_accuracy_m);
end;
$$;

revoke all on function public.fe_report_position(double precision, double precision, double precision) from public, anon;
grant execute on function public.fe_report_position(double precision, double precision, double precision) to authenticated;
