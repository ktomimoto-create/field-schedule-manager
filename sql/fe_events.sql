-- FE のボタン記録（勤務開始 → 出発 → 到着 → 作業完了 → 勤務終了）
-- FE動態（fe-dotai）の fd_events / fd_record_event を予定管理システムへ移したもの。
-- 決定: Vault Projects/field-schedule-manager/Decisions/2026-10-16_FE動態の機能を予定管理システムへ移す.md
--
-- 流し方: Supabase の SQL Editor でこのファイルを丸ごと実行 → 続けて sql/fe_events_check.sql を実行し「確認OK」が出ればよい。
--   既存の表は変えない（schedules / staff は読むのと、RPC から started_at / completed_at / result を書くだけ）。
--
-- 方針:
--   - 位置を含む個人の記録なので、このテーブルは RLS を有効にする（既存の表は RLS 無し運用だが、この表は絞る）
--   - 書き込みは security definer の RPC だけ。誰の記録かは画面から受け取らず、ログイン中のメール → staff で決める
--   - 到着で schedules.started_at、作業完了で schedules.completed_at / result='完了' も書く（今の画面・集計をそのまま使う）
--   - 何度流しても同じ結果になるように書く

create table if not exists public.fe_events (
  id bigint generated by default as identity primary key,
  staff_id bigint not null references public.staff(id) on delete cascade,
  schedule_id bigint references public.schedules(id) on delete set null,
  kind text not null check (kind in ('shift_start', 'depart', 'arrive', 'finish', 'shift_end')),
  occurred_at timestamptz not null default now(),
  -- 記録した日（JST）。勤務開始・終了など予定に紐付かない記録もこの日で引く
  work_date date not null default (now() at time zone 'Asia/Tokyo')::date,
  lat double precision,
  lng double precision,
  accuracy_m double precision,
  created_by_email text,
  created_at timestamptz not null default now()
);

create index if not exists fe_events_date_staff_idx on public.fe_events (work_date, staff_id, occurred_at);
create index if not exists fe_events_schedule_idx on public.fe_events (schedule_id);

alter table public.fe_events enable row level security;

-- 読むのはログインした人だけ（anon キーだけでは読めない）
drop policy if exists fe_events_select_authenticated on public.fe_events;
create policy fe_events_select_authenticated on public.fe_events
  for select to authenticated using (true);

-- 直接の insert / update / delete は誰にも許さない（RPC だけ）
revoke insert, update, delete on public.fe_events from anon, authenticated;
grant select on public.fe_events to authenticated;

-- ログイン中の人の staff.id（見つからなければ null）
create or replace function public.fe_my_staff_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select s.id from public.staff s
  where s.email is not null and lower(trim(s.email)) = lower(trim(auth.email()))
  order by s.id
  limit 1
$$;

-- ボタンを押した記録。返り値は記録した行
create or replace function public.fe_record_event(
  p_kind text,
  p_schedule_id bigint default null,
  p_lat double precision default null,
  p_lng double precision default null,
  p_accuracy_m double precision default null
)
returns public.fe_events
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff bigint := public.fe_my_staff_id();
  v_sched public.schedules%rowtype;
  v_row public.fe_events%rowtype;
  v_now timestamptz := now();
  v_hm text := to_char(now() at time zone 'Asia/Tokyo', 'FMHH24:MI');
begin
  if v_staff is null then
    raise exception 'このアカウントは担当者の名簿（staff）に登録されていません' using errcode = '42501';
  end if;
  if p_kind not in ('shift_start', 'depart', 'arrive', 'finish', 'shift_end') then
    raise exception '記録の種類が正しくありません: %', p_kind using errcode = '22023';
  end if;

  if p_kind in ('depart', 'arrive', 'finish') then
    if p_schedule_id is null then
      raise exception '出発・到着・作業完了は、どの予定かを指定してください' using errcode = '22023';
    end if;
    select * into v_sched from public.schedules where id = p_schedule_id;
    if not found then
      raise exception '予定が見つかりません: %', p_schedule_id using errcode = 'P0002';
    end if;
    if v_sched.staff_id is distinct from v_staff then
      raise exception '自分が対応者の予定だけ記録できます' using errcode = '42501';
    end if;
  end if;

  insert into public.fe_events (staff_id, schedule_id, kind, occurred_at, lat, lng, accuracy_m, created_by_email)
  values (v_staff, case when p_kind in ('depart', 'arrive', 'finish') then p_schedule_id end, p_kind, v_now, p_lat, p_lng, p_accuracy_m, auth.email())
  returning * into v_row;

  -- 今の画面（当日行動予定表・予定表・集計）が読む列にも反映する
  if p_kind = 'arrive' then
    update public.schedules set started_at = v_hm, updated_by = coalesce(auth.email(), updated_by) where id = p_schedule_id;
  elsif p_kind = 'finish' then
    update public.schedules
      set completed_at = v_hm,
          started_at = coalesce(nullif(started_at, ''), v_hm),
          result = '完了',
          updated_by = coalesce(auth.email(), updated_by)
      where id = p_schedule_id;
  end if;

  return v_row;
end;
$$;

-- 押し間違いの取り消し: 自分の今日の最後の記録を 1 件消す（到着・完了で書いた列も戻す）
create or replace function public.fe_undo_last_event()
returns public.fe_events
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff bigint := public.fe_my_staff_id();
  v_row public.fe_events%rowtype;
begin
  if v_staff is null then
    raise exception 'このアカウントは担当者の名簿（staff）に登録されていません' using errcode = '42501';
  end if;
  select * into v_row from public.fe_events
    where staff_id = v_staff and work_date = (now() at time zone 'Asia/Tokyo')::date
    order by occurred_at desc, id desc
    limit 1;
  if not found then
    return null;
  end if;
  delete from public.fe_events where id = v_row.id;
  if v_row.kind = 'arrive' then
    update public.schedules set started_at = null where id = v_row.schedule_id;
  elsif v_row.kind = 'finish' then
    update public.schedules set completed_at = null, result = '' where id = v_row.schedule_id;
  end if;
  return v_row;
end;
$$;

revoke all on function public.fe_my_staff_id() from public, anon;
revoke all on function public.fe_record_event(text, bigint, double precision, double precision, double precision) from public, anon;
revoke all on function public.fe_undo_last_event() from public, anon;
grant execute on function public.fe_my_staff_id() to authenticated;
grant execute on function public.fe_record_event(text, bigint, double precision, double precision, double precision) to authenticated;
grant execute on function public.fe_undo_last_event() to authenticated;
